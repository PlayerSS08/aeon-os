#!/usr/bin/env python3
"""Aeon package repository tool.

    aeon_repo.py keygen [--key .secrets/aeon-repo.key] [--rust src/pkgkey.rs]
    aeon_repo.py build  <src-dir> <out-dir> [--key FILE | --test-key]
    aeon_repo.py pubkey [--key FILE | --test-key]
    aeon_repo.py serve  <dir> [--port 8080]

A package source directory holds `PKGINFO` (Package, Version, Depends, Description) and a `files/` tree whose
paths are relative to `/` on the Aeon machine. `build` turns every package under <src-dir> into a plain
ustar archive (`PKGINFO` first, then directories and files, sorted, no owners, no times, so the output is
reproducible), writes `index` (name, version, depends, size, SHA256, file name) and signs the exact bytes of
`index` with Ed25519 into `index.sig` (128 hex characters). The kernel trusts only the public key compiled
into `src/pkgkey.rs`; keep the private key (default `.secrets/aeon-repo.key`, git-ignored) off the server.

`--test-key` uses a fixed, NON-SECRET key derived from a public phrase. It exists only to build the fixture
repository the unit tests use, and must never sign a real repository.

Needs the `cryptography` package (pip install cryptography). The server only ever needs plain files and
plain HTTP: the signature makes the transport irrelevant.
"""
import argparse
import functools
import hashlib
import http.server
import io
import os
import re
import sys
import tarfile
import time

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_KEY = os.path.join(ROOT, ".secrets", "aeon-repo.key")
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9+.-]{0,31}$")


def test_seed():
    return hashlib.sha256(b"aeon-package-repository-TEST-KEY-not-a-secret").digest()


def load_key(path, use_test):
    if use_test:
        return Ed25519PrivateKey.from_private_bytes(test_seed())
    with open(path, "r", encoding="ascii") as f:
        return Ed25519PrivateKey.from_private_bytes(bytes.fromhex(f.read().strip()))


def public_bytes(sk):
    return sk.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def rust_key_file(pk):
    rows = ", ".join("0x%02x" % b for b in pk)
    return (
        "//! Public key(s) the kernel trusts for package indexes. Generated by `tools/aeon_repo.py keygen`;\n"
        "//! the matching private key is not in the repository (`.secrets/` is git-ignored).\n\n"
        "pub const REPO_KEYS: [[u8; 32]; 1] = [[\n    " + rows + ",\n]];\n"
    )


def cmd_keygen(a):
    if os.path.exists(a.key):
        sys.exit(f"refusing to overwrite {a.key}")
    os.makedirs(os.path.dirname(a.key), exist_ok=True)
    sk = Ed25519PrivateKey.generate()
    seed = sk.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw, serialization.NoEncryption())
    with open(a.key, "w", encoding="ascii") as f:
        f.write(seed.hex() + "\n")
    try:
        os.chmod(a.key, 0o600)
    except OSError:
        pass
    pk = public_bytes(sk)
    with open(a.rust, "w", encoding="utf8", newline="\n") as f:
        f.write(rust_key_file(pk))
    print("private key written to", a.key, "(keep it secret, back it up, never commit it)")
    print("public key", pk.hex(), "written to", a.rust)


def cmd_pubkey(a):
    print(public_bytes(load_key(a.key, a.test_key)).hex())


def parse_pkginfo(path):
    info = {}
    with open(path, "r", encoding="utf8") as f:
        for line in f:
            if ":" in line:
                k, v = line.split(":", 1)
                info[k.strip()] = v.strip()
    for need in ("Package", "Version"):
        if need not in info:
            sys.exit(f"{path}: missing {need}")
    if not NAME_RE.match(info["Package"]):
        sys.exit(f"{path}: bad package name {info['Package']!r}")
    for d in [x.strip() for x in info.get("Depends", "").split(",") if x.strip()]:
        if not NAME_RE.match(d):
            sys.exit(f"{path}: bad dependency name {d!r}")
    return info


def build_tar(pkgdir, info):
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.USTAR_FORMAT) as t:
        def add(name, data=None, directory=False):
            ti = tarfile.TarInfo(name)
            ti.mtime = 0
            ti.uid = ti.gid = 0
            ti.uname = ti.gname = ""
            ti.mode = 0o755 if directory else 0o644
            if directory:
                ti.type = tarfile.DIRTYPE
                t.addfile(ti)
            else:
                ti.size = len(data)
                t.addfile(ti, io.BytesIO(data))

        lines = [f"{k}: {info[k]}" for k in ("Package", "Version", "Depends", "Description") if k in info]
        add("PKGINFO", ("\n".join(lines) + "\n").encode("utf8"))
        files_root = os.path.join(pkgdir, "files")
        dirs, files = set(), []
        for base, _, names in os.walk(files_root):
            for n in names:
                full = os.path.join(base, n)
                rel = os.path.relpath(full, files_root).replace(os.sep, "/")
                if len(rel) > 100 or any(len(c) > 32 for c in rel.split("/")):
                    sys.exit(f"{rel}: Aeon file names are limited to 32 characters per part and 100 in all")
                files.append((rel, full))
                parts = rel.split("/")[:-1]
                for i in range(1, len(parts) + 1):
                    dirs.add("/".join(parts[:i]))
        for d in sorted(dirs):
            add(d, directory=True)
        for rel, full in sorted(files):
            with open(full, "rb") as f:
                add(rel, f.read())
    # tarfile pads the archive to a 10 KiB record; keep just the two zero blocks that mark the end.
    body = buf.getvalue().rstrip(b"\0")
    body += b"\0" * (-len(body) % 512)
    return body + b"\0" * 1024


def cmd_build(a):
    sk = load_key(a.key, a.test_key)
    os.makedirs(os.path.join(a.out, "pool"), exist_ok=True)
    stanzas = []
    for name in sorted(os.listdir(a.src)):
        pkgdir = os.path.join(a.src, name)
        if not os.path.isfile(os.path.join(pkgdir, "PKGINFO")):
            continue
        info = parse_pkginfo(os.path.join(pkgdir, "PKGINFO"))
        data = build_tar(pkgdir, info)
        fname = f"pool/{info['Package']}_{info['Version']}.tar"
        with open(os.path.join(a.out, fname), "wb") as f:
            f.write(data)
        lines = [f"Package: {info['Package']}", f"Version: {info['Version']}"]
        if info.get("Depends"):
            lines.append(f"Depends: {info['Depends']}")
        lines += [f"Size: {len(data)}", f"SHA256: {hashlib.sha256(data).hexdigest()}", f"Filename: {fname}"]
        if info.get("Description"):
            lines.append(f"Description: {info['Description']}")
        stanzas.append("\n".join(lines))
        print(f"packed {info['Package']} {info['Version']}: {len(data)} bytes")
    # The serial grows with every published list; clients refuse an older one (rollback protection).
    serial = a.serial if a.serial is not None else int(time.time())
    index = ("\n\n".join([f"Serial: {serial}"] + stanzas) + "\n").encode("utf8")
    with open(os.path.join(a.out, "index"), "wb") as f:
        f.write(index)
    with open(os.path.join(a.out, "index.sig"), "w", encoding="ascii", newline="\n") as f:
        f.write(sk.sign(index).hex() + "\n")
    print(f"index (serial {serial}) with {len(stanzas)} package(s) signed; public key {public_bytes(sk).hex()}")


def cmd_serve(a):
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=a.dir)
    srv = http.server.ThreadingHTTPServer(("0.0.0.0", a.port), handler)
    print(f"serving {a.dir} on http://0.0.0.0:{a.port}/  (on Aeon: apt source http://<this PC's address>:{a.port}/)")
    srv.serve_forever()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    k = sub.add_parser("keygen")
    k.add_argument("--key", default=DEFAULT_KEY)
    k.add_argument("--rust", default=os.path.join(ROOT, "src", "pkgkey.rs"))
    k.set_defaults(fn=cmd_keygen)
    p = sub.add_parser("pubkey")
    p.add_argument("--key", default=DEFAULT_KEY)
    p.add_argument("--test-key", action="store_true")
    p.set_defaults(fn=cmd_pubkey)
    b = sub.add_parser("build")
    b.add_argument("src")
    b.add_argument("out")
    b.add_argument("--key", default=DEFAULT_KEY)
    b.add_argument("--test-key", action="store_true")
    b.add_argument("--serial", type=int, default=None, help="index serial (default: the current Unix time)")
    b.set_defaults(fn=cmd_build)
    s = sub.add_parser("serve")
    s.add_argument("dir")
    s.add_argument("--port", type=int, default=8080)
    s.set_defaults(fn=cmd_serve)
    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
